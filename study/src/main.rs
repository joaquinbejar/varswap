//! Runs the milestone 5 study and prints `docs/study.md` (`make study` writes it).

// A research harness, like bench/: f64, unwraps on writes to a String, direct indexing.
#![allow(
    clippy::float_arithmetic,
    clippy::print_stdout,
    clippy::cast_precision_loss,
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss,
    clippy::arithmetic_side_effects,
    clippy::integer_division,
    clippy::indexing_slicing,
    clippy::unwrap_used
)]

use std::fmt::Write as _;

use varswap_study::{pusher_bias, run, Model, Params, Rng, Summary};

const PATHS: usize = 4_000;
const SEED: u64 = 0x5EED_5714_D700_0001;
const TOLERANCES: [f64; 5] = [1.0, 3.0, 6.0, 12.0, 24.0];
/// Reporting notional: USDC per unit of annualized variance.
const NOTIONAL_USDC: f64 = 1_000_000.0;

fn vp(x: f64) -> String {
    // Variance points: variance × 10,000.
    format!("{:+.2}", x * 10_000.0)
}

fn usd(x: f64) -> String {
    format!("{:+.0}", x * NOTIONAL_USDC)
}

fn row(out: &mut String, label: &str, tol: f64, unwind: f64, e: &Summary) {
    writeln!(
        out,
        "| {label} | {tol:.0} h | {:.2}% | {} | {} | {} | {} | {} | {} | {} |",
        unwind * 100.0,
        vp(e.mean),
        vp(e.p5),
        vp(e.p50),
        vp(e.p95),
        vp(e.p99),
        usd(e.mean),
        usd(e.p99.abs().max(e.p5.abs())),
    )
    .unwrap();
}

fn main() {
    let base = Params {
        sigma: 0.8,
        n: 720,
        // Assumed exogenous outage regime (no historical source without a Hermes key): one
        // outage every 7 days on average, exponential length with a 1 h mean.
        outage_rate_per_hour: 1.0 / 168.0,
        outage_mean_hours: 1.0,
        halt_trigger_sigmas: 3.0,
        halt_mean_hours: 2.0,
        halt_drift_sigmas: 1.0,
    };
    let models: [(&str, Model); 6] = [
        ("GBM, μ = 0", Model::Gbm { mu: 0.0 }),
        ("GBM, μ = +100%", Model::Gbm { mu: 1.0 }),
        ("AR(1), ρ = +0.3", Model::Ar1 { rho: 0.3 }),
        ("AR(1), ρ = −0.3", Model::Ar1 { rho: -0.3 }),
        ("Halts, continuation", Model::Halts { continuation: true }),
        (
            "Halts, reversal",
            Model::Halts {
                continuation: false,
            },
        ),
    ];

    let mut out = String::new();
    writeln!(out, "# Outage and pusher study").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "Generated by `make study` (`study/`, seed `{SEED:#x}`, {PATHS} windows per model). \
         Window: 30 days hourly (`N = 720`), σ = 80% (SOL-like). Error = contract realized \
         variance (outages compressed into one return, `docs/PLAN.md` 4.1) minus the latent \
         variance of the full grid, over the windows that settle; variance points are \
         variance × 10,000; USDC columns are per {NOTIONAL_USDC:.0} USDC of notional per unit \
         of variance."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "Outage regime (assumed, not historical: Hermes and Benchmarks need an API key, \
         `docs/PLAN.md` verified facts): exogenous outages start at rate 1 per 168 h with an \
         exponential length of mean 1 h. Halt models add endogenous halts: an hourly move \
         above 3 σ_h halts the feed during the move (from inside that hour, across the \
         boundary that ends it, then an exponential time of mean 2 h), and during the halt the \
         latent price drifts 1 σ_h per hour with the move (continuation) or back against it \
         (reversal); the move itself is inside the compressed return."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "| Model | Guard | Unwind | Mean (vp) | p5 (vp) | p50 (vp) | p95 (vp) | p99 (vp) | Mean (USDC) | Tail (USDC) |"
    )
    .unwrap();
    writeln!(
        out,
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"
    )
    .unwrap();
    let mut touched = Vec::new();
    for (i, (label, m)) in models.iter().enumerate() {
        let cells = run(*m, &base, PATHS, SEED.wrapping_add(i as u64), &TOLERANCES);
        for (tol, c) in TOLERANCES.iter().zip(&cells) {
            row(&mut out, label, *tol, c.unwind, &c.error);
        }
        touched.push((label, cells[0].touched, cells[0].mean_latent));
    }
    writeln!(out).unwrap();
    writeln!(out, "Tail (USDC) is max(|p5|, |p99|).").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "| Model | Windows with an outage boundary | Mean latent variance |"
    )
    .unwrap();
    writeln!(out, "| --- | ---: | ---: |").unwrap();
    for (label, t, m) in touched {
        writeln!(out, "| {label} | {:.1}% | {m:.4} |", t * 100.0).unwrap();
    }

    writeln!(out).unwrap();
    writeln!(out, "## Pusher bias without canonical prints").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "If any print within `w` seconds after a boundary were acceptable (first-write-wins \
         with a tolerance), a pusher could steer the contract. The figures are the hindsight \
         optimum over the discrete candidate set: the exact best case for the long (max) and \
         the short (min), by dynamic programming over 7 candidate prints per boundary (one per \
         `w / 6` s), chosen knowing the whole path; a real pusher choosing online gets less. \
         The candidates are taken from the same fine-grained GBM path the hourly prints lie on, σ = 80%, \
         30 days hourly, {} windows; canonical prints make both zero. The control column \
         always takes the last candidate (a fixed shift of `w`): zero in expectation on a \
         coherent path, shown with its standard error.",
        PATHS / 4
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "| w | Long gain mean (vp) | Long gain p95 (vp) | Short gain mean (vp) | Short gain p95 (vp) | Long gain mean (USDC) | Control: fixed shift mean (vp) |"
    )
    .unwrap();
    writeln!(out, "| ---: | ---: | ---: | ---: | ---: | ---: | ---: |").unwrap();
    for w in [10.0, 60.0, 300.0] {
        let mut rng = Rng::new(SEED ^ (w as u64));
        let runs: Vec<_> = (0..PATHS / 4)
            .map(|_| pusher_bias(&base, &mut rng, w, 7))
            .collect();
        let su = varswap_study::summarize(&runs.iter().map(|b| b.long_gain).collect::<Vec<_>>());
        let sd = varswap_study::summarize(&runs.iter().map(|b| b.short_gain).collect::<Vec<_>>());
        let sc = varswap_study::summarize(&runs.iter().map(|b| b.fixed_shift).collect::<Vec<_>>());
        writeln!(
            out,
            "| {w:.0} s | {} | {} | {} | {} | {} | {} ± {:.2} |",
            vp(su.mean),
            vp(su.p95),
            vp(sd.mean),
            vp(sd.p95),
            usd(su.mean),
            vp(sc.mean),
            sc.std / ((PATHS / 4) as f64).sqrt() * 10_000.0
        )
        .unwrap();
    }
    print!("{out}");
}
